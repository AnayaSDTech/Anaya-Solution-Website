// Writes host configuration into the deploy folder:
//  - .htaccess        : Hostinger / Apache / LiteSpeed (clean URLs, redirects, HTTPS, headers, 404)
//  - assets/.htaccess : long-term caching for hashed build assets
//  - _redirects, _headers : Netlify / Cloudflare Pages equivalents (root builds only)
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { loadPublishedProducts } from './load-content.js';
import { site } from '../../src/content/site.js';

const escape = (s) => s.replace(/[.+?^${}()|[\]\\]/g, '\\$&');

async function legacyRedirects() {
  // Old anaya.uk (WordPress) URLs and renamed product slugs → new URLs
  const list = [
    ['home', '/'],
    ['expertise', '/technology'],
    ['career', '/careers'],
  ];
  if (!site.features.servicesPage) list.push(['services', '/products']);
  for (const p of await loadPublishedProducts()) {
    for (const old of p.redirectFrom ?? []) list.push([`products/${old}`, `/products/${p.slug}`]);
  }
  return list;
}

const headersBlock = ({ testCopy }) => `<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set X-Frame-Options "DENY"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
${
  testCopy
    ? '  # Test copy: keep it out of search engines\n  Header always set X-Robots-Tag "noindex, nofollow"'
    : '  Header always set Strict-Transport-Security "max-age=31536000"'
}

  # Pages always revalidate so new uploads show immediately
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
  # Images, fonts and robots/sitemap: cache for a week
  <FilesMatch "\\.(svg|png|jpe?g|webp|avif|ico|woff2?|xml|txt)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
</IfModule>

<IfModule mod_mime.c>
  AddType image/svg+xml .svg
  AddType font/woff2 .woff2
  AddType font/woff .woff
  AddType text/javascript .js .mjs
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/json image/svg+xml application/xml text/plain
</IfModule>
`;

function rootHtaccess(legacy) {
  const host = new URL(site.url).host;
  return `# ANAYA Solutions — live site configuration for Hostinger (LiteSpeed / Apache)
# Generated by scripts/lib/host-config.js — edit that file, not this one.

Options -Indexes -MultiViews
DirectoryIndex index.html
ErrorDocument 404 /__spa-fallback.html

# Pages are pre-rendered as /<page>/index.html but linked without a trailing
# slash (/about). Turn off the automatic "add a slash" redirect; the rules
# below serve the right file instead.
<IfModule mod_dir.c>
  DirectorySlash Off
</IfModule>

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /

  # 1. Force HTTPS and the canonical host (${host}, without www).
  #    Requires the SSL certificate to be active in hPanel.
  RewriteCond %{HTTPS} !=on [OR]
  RewriteCond %{HTTP_HOST} ^www\\. [NC]
  RewriteCond %{HTTP_HOST} ^(?:www\\.)?(.+)$ [NC]
  RewriteRule ^ https://%1%{REQUEST_URI} [R=301,L]

  # 2. Old URLs → new URLs
${legacy.map(([from, to]) => `  RewriteRule ^${escape(from)}/?$ ${to} [R=301,L]`).join('\n')}

  # 3. Canonical URLs have no trailing slash: /about/ → /about
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^(.+)/$ /$1 [R=301,L]

  # 4. Serve the pre-rendered page for a clean URL: /about → /about/index.html
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteCond %{REQUEST_FILENAME}/index.html -f
  RewriteRule ^(.+)$ $1/index.html [L]
</IfModule>

${headersBlock({ testCopy: false })}`;
}

function subfolderHtaccess(base) {
  const folder = base.replace(/\//g, '');
  return `# ANAYA Solutions — TEST COPY served from ${base}
# Upload into public_html/${folder}/. This file only affects ${base}; the rest of
# the domain (including the current WordPress site) is not touched.
# Generated by scripts/lib/host-config.js — edit that file, not this one.

Options -Indexes -MultiViews
DirectoryIndex index.html
ErrorDocument 404 ${base}__spa-fallback.html

<IfModule mod_dir.c>
  DirectorySlash Off
</IfModule>

<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase ${base}

  # 1. HTTPS (the host name is left as it is)
  RewriteCond %{HTTPS} !=on
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L]

  # 2. ${base.slice(0, -1)} → ${base}
  RewriteCond %{REQUEST_URI} ^${escape(base.slice(0, -1))}$
  RewriteRule ^ ${base} [R=301,L]

  # 3. Canonical URLs have no trailing slash: ${base}about/ → ${base}about
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^(.+)/$ ${base}$1 [R=301,L]

  # 4. Serve the pre-rendered page for a clean URL: ${base}about → ${base}about/index.html
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteCond %{REQUEST_FILENAME}/index.html -f
  RewriteRule ^(.+)$ $1/index.html [L]
</IfModule>

${headersBlock({ testCopy: true })}`;
}

export async function writeHostConfig({ outDir, base }) {
  const isRoot = base === '/';
  const legacy = isRoot ? await legacyRedirects() : [];

  await writeFile(path.join(outDir, '.htaccess'), isRoot ? rootHtaccess(legacy) : subfolderHtaccess(base));
  await writeFile(
    path.join(outDir, 'assets', '.htaccess'),
    `<IfModule mod_headers.c>
  Header set Cache-Control "public, max-age=31536000, immutable"
</IfModule>
`,
  );

  if (isRoot) {
    const lines = legacy.flatMap(([from, to]) => [`/${from}  ${to}  301`, `/${from}/  ${to}  301`]);
    await writeFile(path.join(outDir, '_redirects'), lines.join('\n') + '\n');
    await writeFile(
      path.join(outDir, '_headers'),
      `/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
  X-Frame-Options: DENY
  Strict-Transport-Security: max-age=31536000

/assets/*
  Cache-Control: public, max-age=31536000, immutable
`,
    );
  }
  return { legacyCount: legacy.length };
}
